/**
 * Build `lib/client.js` from `locales/ru/<namespace>.json`.
 *
 * The browser module system consumes a single self-registering bundle, so the
 * per-namespace files stay reviewable and this script inlines them in the exact
 * shape `window.__ModuleLoader__` expects (see @deepseek-ai/dsh-client-modules).
 *
 * The output is deterministic: the same sources always produce the same bytes,
 * which is what makes the committed artifact verifiable (see tools/audit-bundle.js
 * and .github/workflows/verify.yml).
 *
 * Run: node tools/build.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.dirname(toolsDir);
const localesDir = path.join(root, 'locales', 'ru');
const outFile = path.join(root, 'lib', 'client.js');

const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const PACKAGE_ID = manifest.name;
const LANGUAGE = { id: 'ru', label: 'Русский', fallback: 'en' };

const files = fs.existsSync(localesDir)
  ? fs.readdirSync(localesDir).filter((f) => f.endsWith('.json')).sort()
  : [];

const dictionaries = {};
let keyCount = 0;
for (const file of files) {
  const ns = path.basename(file, '.json');
  const dict = JSON.parse(fs.readFileSync(path.join(localesDir, file), 'utf8'));
  const keys = Object.keys(dict);
  if (keys.length === 0) continue;
  keyCount += keys.length;
  dictionaries[ns] = dict;
}

const namespaces = Object.keys(dictionaries).sort();

const bundle = `// Generated by tools/build.js — do not edit by hand.
// Russian language pack for the DeepSeek Harness web GUI.
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(PACKAGE_ID)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
\t\tconst LANGUAGE = ${JSON.stringify(LANGUAGE)};
\t\tconst DICTIONARIES = ${JSON.stringify(dictionaries, null, '\t').replace(/\n/g, '\n\t\t')};
\t\t/** Client plugin body: register the language, then each translated namespace. */
\t\tfunction apply(ctx) {
\t\t\tctx.effect(() => ctx.locale.addLanguage(LANGUAGE), ${JSON.stringify(PACKAGE_ID + ': language')});
\t\t\tfor (const ns of Object.keys(DICTIONARIES)) {
\t\t\t\tctx.effect(() => ctx.locale.register(ns, LANGUAGE.id, DICTIONARIES[ns]), ${JSON.stringify(PACKAGE_ID + ': ')} + ns);
\t\t\t}
\t\t}
\t\texports.apply = apply;
\t\texports.inject = ["locale"];
\t\treturn module.exports;
\t}
});
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, bundle, 'utf8');

console.log(`${PACKAGE_ID}: ${namespaces.length} namespaces, ${keyCount} keys -> lib/client.js`);
